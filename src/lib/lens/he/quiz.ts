/** A bank question in Hebrew (choices keep the same order, so the answer index still holds). */
export function heQuestion(q: QuizQ): QuizQ {
  const h = QUIZ_HE[q.id];
  return h && h.choices.length === q.choices.length ? { ...q, ...h } : q;
}

/** Questions about the ticker on screen, in Hebrew (from the English payload). */
export function heTickerQuestions(p: LensPayload): QuizQ[] {
  const out: QuizQ[] = [];
  const S = ltr(p.symbol);
  const all = p.cards.flatMap((c) => c.metrics.map((m) => ({ m, c })));
  if (p.lifeCycle) {
    const order = ["startup", "young_growth", "high_growth", "mature_growth", "mature_stable", "decline"] as const;
    const i = order.indexOf(p.lifeCycle.stage);
    const pick = order.filter((s) => s !== p.lifeCycle!.stage).sort((a, b) => Math.abs(order.indexOf(a) - i) - Math.abs(order.indexOf(b) - i)).slice(0, 3);
    const keys = [...pick, p.lifeCycle.stage].sort((a, b) => order.indexOf(a) - order.indexOf(b));
    out.push({ id: `t:${p.symbol}:stage`, concept: "life_cycle", q: `איפה האפליקציה מיקמה את ${S} במחזור החיים?`, choices: keys.map((k) => HE_STAGE[k].label),
      answer: keys.indexOf(p.lifeCycle.stage), why: `${HE_STAGE[p.lifeCycle.stage].label}: ${HE_STAGE[p.lifeCycle.stage].signature}` });
  }
  const benchM = all.find(({ m }) => ["op_margin", "gross_margin", "roic", "sales_to_capital"].includes(m.id) && m.bench);
  if (benchM) {
    const { m } = benchM;
    const ans = m.bench!.position === "above" ? 0 : m.bench!.position === "in line" ? 1 : 2;
    out.push({ id: `t:${p.symbol}:bench:${m.id}`, concept: benchM.c.id,
      q: `${HE_METRIC[m.id]?.label ?? m.label} של ${S} הוא ${ltr(m.display)}. בהשוואה לממוצע של דמודרן לענף ${m.bench!.industry}, הוא…`,
      choices: ["מעל ממוצע הענף", "בקו אחד איתו", "מתחתיו"], answer: ans,
      why: `ממוצע הענף הוא ${ltr(m.bench!.display)} (השוק כולו ${ltr(m.bench!.market ?? "אין נתון")}). עד כעשירית מהממוצע נחשב בקו אחד.` });
  }
  const ex = all.find(({ m }) => m.id === "excess_return" && m.value !== null);
  if (ex) {
    const v = ex.m.value as number;
    out.push({ id: `t:${p.symbol}:spread`, concept: "value_creation", q: `האם התשואה על ההון של ${S} עולה על מה שעולה ההון בענף שלה?`,
      choices: ["כן — צמיחה בתשואות כאלה מוסיפה ערך", "בערך נקודת איזון", "לא — צמיחה בתשואות כאלה עדיין לא מוסיפה ערך"], answer: v > 1 ? 0 : v < -1 ? 2 : 1,
      why: `התשואה על ההון פחות עלות ההון בענף: ${ltr(ex.m.display)}. עד ${ltr("±1")} נקודת אחוז נחשב כאן נקודת איזון.` });
  }
  const peer = all.find(({ m }) => m.id === "rev_growth_ttm" && m.peer) as { m: Metric } | undefined;
  if (peer?.m.peer) {
    const pos = peer.m.peer.position;
    if (pos === "top" || pos === "middle" || pos === "bottom") {
      out.push({ id: `t:${p.symbol}:peer`, concept: "revenue_growth", q: `ההכנסות של ${S} צמחו ב-${ltr(peer.m.display)}. מתוך ${ltr(peer.m.peer.n)} חברות ${peer.m.peer.group} באפליקציה, זה מדורג…`,
        choices: ["בחמישון העליון", "בערך באמצע", "בחמישון התחתון"], answer: pos === "top" ? 0 : pos === "middle" ? 1 : 2,
        why: `האחוזון ה-${ltr(peer.m.peer.pct)}; החציון של החברות הדומות הוא ${ltr(peer.m.peer.median)}.` });
    }
  }
  return out;
}
